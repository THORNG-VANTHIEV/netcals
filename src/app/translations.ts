export function translateDynamicError(message:string,t:(text:string)=>string):string {
  const translated=t(message)
  if(translated!==message)return translated
  if(/^Requirement \d+ needs a name\.$/.test(message))return message.replace('Requirement',t('Requirement')).replace('needs a name.',t('needs a name.'))
  const split=message.indexOf(': ')
  if(split>=0)return `${message.slice(0,split)}: ${t(message.slice(split+2))}`
  return t(message)
}
