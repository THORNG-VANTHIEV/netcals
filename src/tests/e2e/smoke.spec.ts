test('calculator follows browser history after multiple calculations',async({page})=>{
  await page.goto('/#/tools/subnet-calculator?ip=192.168.1.10&prefix=26')
  await expect(page.getByText('192.168.1.0/26',{exact:true})).toBeVisible()
  await page.getByLabel('CIDR prefix or subnet mask').fill('27')
  await page.getByRole('button',{name:'Calculate subnet'}).click()
  await expect(page.getByText('192.168.1.0/27',{exact:true})).toBeVisible()
  await expect(page).toHaveURL(/prefix=27/)
  await page.goBack()
  await expect(page).toHaveURL(/prefix=26/)
  await expect(page.getByLabel('CIDR prefix or subnet mask')).toHaveValue('26')
  await expect(page.getByText('192.168.1.0/26',{exact:true})).toBeVisible()
  await page.goForward()
  await expect(page.getByLabel('CIDR prefix or subnet mask')).toHaveValue('27')
  await expect(page.getByText('192.168.1.0/27',{exact:true})).toBeVisible()
})
test('Khmer interface keeps network terms, persists, and fits a narrow phone',async({page})=>{
  await page.setViewportSize({width:320,height:720})
  await page.goto('/#/tools/subnet-calculator')
  await page.getByRole('button',{name:'Switch to Khmer'}).click()
  await expect(page.locator('html')).toHaveAttribute('lang','km')
  await expect(page.locator('main h1')).toContainText('Subnet')
  await expect(page.locator('main h1')).toContainText('ឧបករណ៍គណនា')
  await page.getByLabel('IPv4 address').fill('192.168.1.999')
  await page.getByRole('button',{name:/គណនា Subnet/}).click()
  await expect(page.getByRole('alert')).toContainText('បញ្ចូល IPv4 address')
  for(const route of ['/','/tools/flsm-calculator','/tools/vlsm-calculator','/tools/cidr-converter','/tools/binary-visualizer','/reference/subnet-table','/learn/subnetting']){
    await page.goto(`/#${route}`)
    await expect(page.locator('main h1')).toHaveCount(1)
    await expect(page.getByRole('button',{name:'ប្តូរទៅ English'})).toBeVisible()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),route).toBe(false)
  }
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('lang','km')
  await page.getByRole('button',{name:'ប្តូរទៅ English'}).click()
  await expect(page.locator('html')).toHaveAttribute('lang','en')
  await expect(page.locator('main h1')).toHaveText('Learn Subnetting')
})
