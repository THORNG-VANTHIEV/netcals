import {test,expect} from '@playwright/test'
test('all MVP routes render and the subnet calculator works',async({page})=>{
  const routes=['/','/tools/subnet-calculator','/tools/flsm-calculator','/tools/vlsm-calculator','/tools/cidr-converter','/tools/binary-visualizer','/reference/subnet-table','/learn/subnetting']
  for(const route of routes){await page.goto(`/#${route}`);await expect(page.locator('main h1')).toHaveCount(1)}
  await page.goto('/#/tools/subnet-calculator')
  await page.getByLabel('IPv4 address').fill('192.168.1.10')
  await page.getByLabel('CIDR prefix or subnet mask').fill('26')
  await page.getByRole('button',{name:'Calculate subnet'}).click()
  await expect(page.getByText('192.168.1.0/26',{exact:true})).toBeVisible()
  await expect(page.getByText('192.168.1.63')).toBeVisible()
  await page.getByLabel('IPv4 address').fill('192.168.1.999')
  await page.getByRole('button',{name:'Calculate subnet'}).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByText('192.168.1.0/26',{exact:true})).toHaveCount(0)
  await page.goto('/#/tools/subnet-calculator?ip=192.168.1.999&prefix=24')
  await expect(page.getByRole('alert')).toContainText('valid IPv4 address')
})
