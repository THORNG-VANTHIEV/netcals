test('mobile routes have no whole-page horizontal overflow',async({page})=>{
  await page.setViewportSize({width:320,height:720})
  for(const route of ['/','/tools/subnet-calculator','/tools/flsm-calculator','/tools/vlsm-calculator','/tools/cidr-converter','/tools/binary-visualizer','/reference/subnet-table','/learn/subnetting']){
    await page.goto(`/#${route}`)
    await expect(page.getByRole('navigation',{name:'Mobile navigation'})).toBeVisible()
    await expect(page.getByRole('button',{name:'More tools'})).toBeVisible()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),route).toBe(false)
  }
  await page.getByRole('button',{name:'Switch to dark theme'}).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark')
})
test('phone navigation, search and touch targets work',async({page})=>{
  await page.setViewportSize({width:320,height:720})
  await page.goto('/#/tools/subnet-calculator')
  await page.getByRole('button',{name:'More tools'}).click()
  await expect(page.getByRole('dialog',{name:'Main navigation'})).toBeVisible()
  await page.getByRole('dialog').getByRole('link',{name:'CIDR Converter'}).click()
  await expect(page.locator('main h1')).toHaveText('CIDR Converter')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button',{name:'Search tools'}).click()
  await page.getByRole('textbox',{name:'Search tools'}).fill('Binary')
  await page.getByRole('button',{name:'Binary Visualizer'}).click()
  await expect(page.locator('main h1')).toHaveText('Binary Visualizer')
  await expect(page.getByRole('textbox',{name:'Search tools'})).toBeHidden()
  await page.getByRole('navigation',{name:'Mobile navigation'}).getByRole('link',{name:'Subnet'}).click()
  const preset=page.getByRole('button',{name:'/26'})
  expect(await preset.evaluate(element=>element.getBoundingClientRect().height)).toBeGreaterThanOrEqual(44)
  expect(await page.getByLabel('IPv4 address').evaluate(element=>Number.parseFloat(getComputedStyle(element).fontSize))).toBeGreaterThanOrEqual(16)
  await page.getByLabel('IPv4 address').focus()
  await expect(page.getByRole('navigation',{name:'Mobile navigation'})).toBeHidden()
})
